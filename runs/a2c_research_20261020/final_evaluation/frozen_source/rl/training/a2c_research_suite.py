"""Resume the isolated A2C development queue; never launch final tests.

Existing phase-1/phase-2 results are development inputs. The expert dataset is
generated by a separate, authorized process; this queue only waits for its
verified completion. Child training owns its original OS run.lock. Launcher
records/logs deliberately live outside training directories, since a new
training directory must be empty. Killing this supervisor never kills a child.

Usage: python -u -m rl.training.a2c_research_suite --device cuda
Inspect the concrete commands without starting work with --plan-only.
"""

from __future__ import annotations

import argparse
